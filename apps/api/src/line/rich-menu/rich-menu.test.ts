import { describe, it, expect, beforeEach, vi } from 'vitest';
import { BadRequestException, NotFoundException } from '@nestjs/common';
import { LineRichMenuService } from './line-rich-menu.service';
import { LineAdminController } from '../../admin/line-admin.controller';
import { LineMessagingService } from '../messaging/line-messaging.service';
import { LineMessageTemplateService } from '../messaging/line-message-template.service';

describe('Phase 5 — LINE Rich Menu & Flex Message Integration', () => {
  let richMenuService: LineRichMenuService;
  let lineMessagingService: LineMessagingService;
  let templateService: LineMessageTemplateService;
  let adminController: LineAdminController;
  let mockDb: any;

  beforeEach(async () => {
    // Mock Database
    mockDb = {
      prisma: {
        $queryRawUnsafe: vi.fn().mockResolvedValue([]),
        $executeRawUnsafe: vi.fn().mockResolvedValue(1),
      },
      findUserByLineUserId: vi.fn().mockImplementation(async (lineId: string) => {
        if (lineId === 'U-citizen-01') return { id: 'u-1', role: 'USER' };
        if (lineId === 'U-staff-01') return { id: 'u-2', role: 'STAFF' };
        if (lineId === 'U-admin-01') return { id: 'u-3', role: 'ADMIN' };
        return null;
      }),
    };

    // Instantiate real services (in mock mode)
    lineMessagingService = new LineMessagingService();
    templateService = new LineMessageTemplateService();
    richMenuService = new LineRichMenuService(mockDb, lineMessagingService, templateService);
    adminController = new LineAdminController(richMenuService);

    // Initialize default menus
    await richMenuService.seedDefaultMenus();
  });

  describe('1. Rich Menu Blueprint & Defaults Seeding', () => {
    it('seeds 4 distinct default rich menus (Citizen, Staff, Admin, Guest)', async () => {
      const menus = await richMenuService.listRichMenus();
      expect(menus.length).toBe(4);

      const citizen = menus.find((m) => m.menuType === 'CITIZEN');
      expect(citizen).toBeDefined();
      expect(citizen?.actions.length).toBe(6);
      expect(citizen?.chatBarText).toBe('บริการประชาชน');

      const staff = menus.find((m) => m.menuType === 'STAFF');
      expect(staff).toBeDefined();
      expect(staff?.actions.length).toBe(6);
      expect(staff?.chatBarText).toBe('งานเจ้าหน้าที่');

      const admin = menus.find((m) => m.menuType === 'ADMIN');
      expect(admin).toBeDefined();
      expect(admin?.actions.length).toBe(6);
      expect(admin?.chatBarText).toBe('จัดการระบบ');

      const guest = menus.find((m) => m.menuType === 'DEFAULT');
      expect(guest).toBeDefined();
      expect(guest?.isDefault).toBe(true);
      expect(guest?.chatBarText).toBe('เมนูจับจอง');
    });

    it('verifies citizen menu routes point to legitimate JapJong LIFF targets', async () => {
      const menus = await richMenuService.listRichMenus();
      const citizen = menus.find((m) => m.menuType === 'CITIZEN');
      const actionUris = citizen?.actions.map((a) => a.actionData) || [];

      expect(actionUris).toContain('/booking');
      expect(actionUris).toContain('/borrow');
      expect(actionUris).toContain('/repair');
      expect(actionUris).toContain('/requests');
      expect(actionUris).toContain('/documents');
    });
  });

  describe('2. LINE Specification Validation (Image, Size, Coordinates)', () => {
    it('validates 2500x1686 PNG image generated by internal engine', () => {
      const pngBuffer = richMenuService.generateDefaultRichMenuPng(
        'Test Menu',
        [{ label: 'Tile 1' }, { label: 'Tile 2' }],
        '#0F4C81',
      );
      expect(pngBuffer.length).toBeGreaterThan(0);

      const check = richMenuService.validateRichMenuImage(pngBuffer, 'image/png');
      expect(check.valid).toBe(true);
      expect(check.width).toBe(2500);
      expect(check.height).toBe(1686);
    });

    it('rejects image with wrong aspect ratio or size exceeding 1MB', () => {
      // 100x100 is not allowed by LINE spec (ratio 1:1)
      const invalidPng = Buffer.alloc(500);
      // Mock minimal png header with 100x100
      invalidPng[0] = 0x89;
      invalidPng[1] = 0x50;
      invalidPng[2] = 0x4e;
      invalidPng[3] = 0x47;
      invalidPng.writeUInt32BE(100, 16);
      invalidPng.writeUInt32BE(100, 20);

      const check = richMenuService.validateRichMenuImage(invalidPng, 'image/png');
      expect(check.valid).toBe(false);
      expect(check.error).toContain('ความกว้างต้องอยู่ระหว่าง 800 ถึง 2500 px');

      // Reject file > 1MB
      const largeBuf = Buffer.alloc(1048576 + 10);
      const checkLarge = richMenuService.validateRichMenuImage(largeBuf, 'image/png');
      expect(checkLarge.valid).toBe(false);
      expect(checkLarge.error).toContain('เกินขีดจำกัด 1 MB');
    });

    it('rejects action coordinates exceeding menu dimensions', async () => {
      await expect(
        richMenuService.createRichMenu({
          name: 'Invalid Bounds Menu',
          menuType: 'CUSTOM',
          chatBarText: 'เมนูทดสอบ',
          width: 2500,
          height: 1686,
          actions: [
            {
              label: 'Out of bounds',
              actionType: 'URI',
              actionData: '/booking',
              area: { x: 2000, y: 1000, width: 800, height: 800 }, // 2000 + 800 = 2800 > 2500
            },
          ],
        }),
      ).rejects.toThrow(BadRequestException);
    });

    it('rejects action URI containing security credentials or secrets', async () => {
      await expect(
        richMenuService.createRichMenu({
          name: 'Insecure Menu',
          menuType: 'CUSTOM',
          chatBarText: 'เมนูทดสอบ',
          width: 2500,
          height: 1686,
          actions: [
            {
              label: 'Leak Token',
              actionType: 'URI',
              actionData: '/login?token=supersecret123',
              area: { x: 0, y: 0, width: 800, height: 800 },
            },
          ],
        }),
      ).rejects.toThrow(/ห้ามใส่ Token หรือ Secret/);
    });
  });

  describe('3. Publishing & Default Settings', () => {
    it('publishes rich menu to LINE and assigns lineRichMenuId', async () => {
      const menus = await richMenuService.listRichMenus();
      const citizen = menus.find((m) => m.menuType === 'CITIZEN')!;

      const published = await richMenuService.publishRichMenu(citizen.id);
      expect(published.status).toBe('PUBLISHED');
      expect(published.lineRichMenuId).toBeDefined();
      expect(published.lineRichMenuId).toContain('mock');
    });

    it('sets a published menu as default for LINE OA', async () => {
      const menus = await richMenuService.listRichMenus();
      const guest = menus.find((m) => m.menuType === 'DEFAULT')!;

      const def = await richMenuService.setDefaultRichMenu(guest.id);
      expect(def.isDefault).toBe(true);
      expect(def.lineRichMenuId).toBeDefined();
    });
  });

  describe('4. Role-Based Rich Menu Switching (Security Strict)', () => {
    it('switches citizen to CITIZEN rich menu when role is USER', async () => {
      // Publish citizen menu first
      const menus = await richMenuService.listRichMenus();
      const citizen = menus.find((m) => m.menuType === 'CITIZEN')!;
      await richMenuService.publishRichMenu(citizen.id);

      const res = await richMenuService.switchUserRichMenuByRole('U-citizen-01', 'USER');
      expect(res.switched).toBe(true);
      expect(res.menuType).toBe('CITIZEN');
      expect(res.richMenuId).toBe(citizen.id);
    });

    it('switches staff to STAFF rich menu when role is STAFF or APPROVER', async () => {
      const menus = await richMenuService.listRichMenus();
      const staff = menus.find((m) => m.menuType === 'STAFF')!;
      await richMenuService.publishRichMenu(staff.id);

      const resStaff = await richMenuService.switchUserRichMenuByRole('U-staff-01', 'STAFF');
      expect(resStaff.switched).toBe(true);
      expect(resStaff.menuType).toBe('STAFF');

      const resApprover = await richMenuService.switchUserRichMenuByRole('U-palad-01', 'APPROVER_L2');
      expect(resApprover.switched).toBe(true);
      expect(resApprover.menuType).toBe('STAFF');
    });

    it('switches admin to ADMIN rich menu when role is ADMIN', async () => {
      const menus = await richMenuService.listRichMenus();
      const admin = menus.find((m) => m.menuType === 'ADMIN')!;
      await richMenuService.publishRichMenu(admin.id);

      const res = await richMenuService.switchUserRichMenuByRole('U-admin-01', 'ADMIN');
      expect(res.switched).toBe(true);
      expect(res.menuType).toBe('ADMIN');
      expect(res.richMenuId).toBe(admin.id);
    });

    it('unlinks rich menu for unauthenticated guests so LINE shows default menu', async () => {
      const res = await richMenuService.switchUserRichMenuByRole('U-guest-01', undefined);
      expect(res.switched).toBe(true);
      expect(res.menuType).toBe('DEFAULT');
    });
  });

  describe('5. Flex Message Templates & Dynamic Overrides', () => {
    it('renders clean Flex Message preview for booking approval', () => {
      const preview = richMenuService.previewFlexTemplate('BOOKING_APPROVED', {
        requestCode: 'BK-20261104-001',
        venueName: 'ห้องประชุมเทศบาล',
      });

      expect(preview).toBeDefined();
      expect(preview.inAppTitle).toContain('อนุมัติ');
      expect(preview.lineMessages.length).toBeGreaterThan(0);
      expect(preview.lineMessages[0].type).toBe('flex');
    });

    it('applies custom dynamic template override saved in Supabase', async () => {
      await richMenuService.upsertFlexTemplate({
        name: 'คำขออนุมัติพิเศษ',
        eventType: 'BOOKING_APPROVED',
        templateType: 'FLEX',
        status: 'ACTIVE',
        content: {
          headline: 'หัวข้อปรับแต่งพิเศษ: อนุมัติผ่านระบบ',
          footerNote: 'ติดต่อเจ้าหน้าที่โทร 054-000000',
          headerColor: '#10B981',
          buttonLabel: 'ตรวจสอบเอกสารอนุมัติ',
        },
      });

      const list = await richMenuService.listFlexTemplates();
      expect(list.length).toBeGreaterThan(0);
      expect(list.some((t) => t.eventType === 'BOOKING_APPROVED')).toBe(true);
    });
  });

  describe('6. Admin Controller Endpoints Integration', () => {
    it('provides CRUD endpoints for rich menu management', async () => {
      const all = await adminController.listRichMenus();
      expect(all.length).toBe(4);

      const first = all[0];
      const detail = await adminController.getRichMenu(first.id);
      expect(detail.id).toBe(first.id);

      const updated = await adminController.updateRichMenu(first.id, {
        chatBarText: 'เมนูใหม่',
      });
      expect(updated.chatBarText).toBe('เมนูใหม่');
    });

    it('supports direct user link and unlink API for testing', async () => {
      const all = await adminController.listRichMenus();
      const citizen = all.find((m) => m.menuType === 'CITIZEN')!;
      await adminController.publishRichMenu(citizen.id);

      const linkRes = await adminController.linkUser({
        lineUserId: 'U11112222',
        richMenuId: citizen.id,
      });
      expect(linkRes.success).toBe(true);

      const unlinkRes = await adminController.unlinkUser({
        lineUserId: 'U11112222',
      });
      expect(unlinkRes.success).toBe(true);
    });
  });
});

